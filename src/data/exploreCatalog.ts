/**
 * SVG Generator helper for high-contrast, bold grainy bento style sticker artwork
 */
function createStickerSvg(
  primaryText: string,
  emoji: string,
  bgGradient: [string, string],
  textColor: string = "#FFFFFF",
  subText: string = ""
): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgGradient[0]}" />
        <stop offset="100%" stop-color="${bgGradient[1]}" />
      </linearGradient>
      <filter id="shadow" x="-10%" y="-10%" width="130%" height="130%">
        <feDropShadow dx="0" dy="12" stdDeviation="16" flood-color="#000000" flood-opacity="0.35" />
      </filter>
      <filter id="whiteStroke">
        <feMorphology operator="dilate" radius="8" />
        <feComposite in="SourceGraphic" in2="BackgroundImage" operator="over" />
      </filter>
    </defs>
    
    <!-- Outer Sticker Die-Cut Border -->
    <rect x="24" y="24" width="464" height="464" rx="96" fill="#FFFFFF" filter="url(#shadow)" />
    <!-- Inner Colored Sticker Body -->
    <rect x="36" y="36" width="440" height="440" rx="84" fill="url(#g)" />
    
    <!-- Top Emoji Focal Point -->
    <text x="256" y="220" font-size="140" text-anchor="middle" dominant-baseline="central">${emoji}</text>
    
    <!-- Primary Bold Headline -->
    <text x="256" y="340" font-family="'Space Grotesk', -apple-system, BlinkMacSystemFont, sans-serif" font-weight="900" font-size="44" fill="${textColor}" text-anchor="middle" letter-spacing="1">
      ${primaryText}
    </text>
    
    <!-- Subtitle Banner if provided -->
    ${
      subText
        ? `<rect x="100" y="380" width="312" height="42" rx="14" fill="#000000" fill-opacity="0.25" />
           <text x="256" y="408" font-family="'Space Grotesk', sans-serif" font-weight="800" font-size="20" fill="#FFFFFF" text-anchor="middle">
             ${subText}
           </text>`
        : ""
    }
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

